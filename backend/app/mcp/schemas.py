"""Pydantic schemas for CUSTODE MCP Security Layer."""

from datetime import datetime
from typing import Any, Dict, List, Optional
import uuid

from pydantic import BaseModel, ConfigDict, Field


class MCPServerCreate(BaseModel):
    """Payload to register a new external MCP server boundary."""
    name: str = Field(..., min_length=1, max_length=255, description="Human-readable server name")
    slug: Optional[str] = Field(None, max_length=100, description="Unique slug; autogenerated if omitted")
    description: Optional[str] = Field(None, max_length=1000, description="Server description")
    server_type: str = Field("REMOTE", description="Controlled server type (REMOTE, LOCAL, INTERNAL, THIRD_PARTY, CUSTOM)")
    endpoint: str = Field(..., max_length=500, description="Server destination URL or address")
    transport: str = Field("HTTP", description="MCP transport protocol (HTTP, SSE, STREAMABLE_HTTP, STDIO, MOCK)")
    trust_level: str = Field("UNTRUSTED", description="Contextual trust tier (UNTRUSTED, VERIFIED, TRUSTED)")
    environment: str = Field("development", description="Deployment tier (development, staging, production)")
    metadata: Optional[Dict[str, Any]] = Field(None, description="Optional administrative server metadata")


class MCPServerUpdate(BaseModel):
    """Payload to update an existing MCP server registration."""
    name: Optional[str] = Field(None, min_length=1, max_length=255)
    description: Optional[str] = Field(None, max_length=1000)
    endpoint: Optional[str] = Field(None, max_length=500)
    transport: Optional[str] = None
    trust_level: Optional[str] = None
    environment: Optional[str] = None
    metadata: Optional[Dict[str, Any]] = None


class MCPServerResponse(BaseModel):
    """Authoritative API representation of an MCP server."""
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    organization_id: uuid.UUID
    name: str
    slug: str
    description: Optional[str] = None
    server_type: str
    endpoint: str
    transport: str
    status: str
    trust_level: str
    environment: str
    metadata: Optional[Dict[str, Any]] = Field(None, alias="server_metadata")
    created_at: datetime
    updated_at: datetime
    tool_count: int = 0


class MCPServerListResponse(BaseModel):
    """Paginated list of registered MCP servers."""
    items: List[MCPServerResponse]
    total: int


class MCPToolResponse(BaseModel):
    """Authoritative representation of a discovered or active MCP tool."""
    model_config = ConfigDict(from_attributes=True)

    id: uuid.UUID
    organization_id: uuid.UUID
    mcp_server_id: uuid.UUID
    tool_id: Optional[uuid.UUID] = None
    operation_id: Optional[uuid.UUID] = None
    name: str
    slug: str
    description: Optional[str] = None
    input_schema: Dict[str, Any]
    output_schema: Optional[Dict[str, Any]] = None
    status: str
    risk_level: str
    schema_hash: str
    previous_schema_hash: Optional[str] = None
    schema_changed: bool = False
    discovered_at: datetime
    activated_at: Optional[datetime] = None
    metadata: Optional[Dict[str, Any]] = Field(None, alias="tool_metadata")
    created_at: datetime
    updated_at: datetime


class MCPToolListResponse(BaseModel):
    """Paginated list of discovered or active MCP tools."""
    items: List[MCPToolResponse]
    total: int


class MCPDiscoveryResponse(BaseModel):
    """Summary of an MCP server discovery operation."""
    server_id: uuid.UUID
    discovered_count: int
    new_tools_count: int
    updated_tools_count: int
    schema_drift_count: int
    findings_count: int
    tools: List[MCPToolResponse]
    findings: List[Dict[str, Any]] = Field(default_factory=list)


class MCPToolCallRequest(BaseModel):
    """Payload to invoke a controlled MCP tool call."""
    arguments: Dict[str, Any] = Field(default_factory=dict, description="Parameters matching tool input_schema")
    agent_id: Optional[uuid.UUID] = Field(None, description="Optional agent UUID invoking the tool")


class MCPToolCallResponse(BaseModel):
    """Result of an MCP tool invocation mediated by the CUSTODE control plane."""
    tool_id: uuid.UUID
    runtime_action_id: uuid.UUID
    decision: str
    status: str
    result: Optional[Any] = None
    approval_id: Optional[uuid.UUID] = None
    latency_ms: float = 0.0
    input_findings: List[Dict[str, Any]] = Field(default_factory=list)
    output_findings: List[Dict[str, Any]] = Field(default_factory=list)
    error: Optional[str] = None


class MCPMetricsResponse(BaseModel):
    """Aggregated MCP security and governance telemetry."""
    total_servers: int
    active_servers: int
    suspended_servers: int
    total_tools: int
    active_tools: int
    discovered_tools: int
    schema_drift_tools: int
    total_findings: int
    total_calls: int
    blocked_calls: int
